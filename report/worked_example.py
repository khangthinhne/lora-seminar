"""Generate ``report/worked_example.md``: a hand-checkable LoRA example.

Hypothesis: one LoRA gradient step changes only ``B`` when ``B`` starts at zero,
and the resulting forward pass equals ``W0 x + (alpha/r) B (A x)``. Setup:
d = k = 4, r = 1, alpha = 2, identity ``W0``, one sample, MSE loss, one SGD
step with lr = 0.1. Expected outcome: the hand-derived gradients match
``torch.autograd`` and the post-step output matches the merged form exactly
(up to float32 rounding).
"""

from __future__ import annotations

from pathlib import Path

import torch
from torch.nn import functional as F

from lora_lab.methods.lora import LoRALinear
from lora_lab.metrics import mse

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / "report" / "worked_example.md"
SOURCE = "Team experiment (toy, synthetic)."
LR = 0.1


def main() -> int:
    """Run the example, validate autograd, and write the Markdown asset."""
    d, k, r, alpha = 4, 4, 1, 2.0
    scaling = alpha / r
    w0 = torch.eye(d)
    a_matrix = torch.tensor([[1.0, 0.0, 0.0, 0.0]])
    x = torch.tensor([[1.0, 2.0, 0.0, 1.0]])
    y = torch.tensor([[2.0, 1.0, 0.0, 1.0]])

    layer = LoRALinear(w0, r=r, alpha=alpha, init_std=0.5)
    with torch.no_grad():
        layer.A.copy_(a_matrix)
        layer.B.zero_()

    base = F.linear(x, w0)
    initial = layer(x)
    initial_delta = layer.effective_delta()
    initial_loss = mse(initial, y)

    loss = mse(layer(x), y)
    loss.backward()
    a_grad = layer.A.grad.detach().clone()
    b_grad = layer.B.grad.detach().clone()

    diff = initial - y
    n_samples, d_out = x.shape[0], d
    d_loss_du = (2.0 / (n_samples * d_out)) * diff
    z = x @ layer.A.T
    hand_b_grad = layer.scaling * (d_loss_du.T @ z)
    hand_a_grad = layer.scaling * (((d_loss_du @ layer.B).T) @ x)

    torch.testing.assert_close(b_grad, hand_b_grad, atol=1e-7, rtol=1e-6)
    torch.testing.assert_close(a_grad, hand_a_grad, atol=1e-7, rtol=1e-6)
    assert torch.count_nonzero(a_grad) == 0
    assert torch.count_nonzero(initial_delta) == 0
    assert torch.equal(initial, base)

    optimizer = torch.optim.SGD(layer.parameters(), lr=LR)
    optimizer.step()
    updated_delta = layer.effective_delta().detach()
    updated = layer(x)
    merged = layer.merge()
    merged_output = merged(x)
    torch.testing.assert_close(updated, merged_output, atol=1e-6, rtol=1e-5)

    rank_path = base + layer.scaling * ((x @ layer.A.T) @ layer.B.T)
    torch.testing.assert_close(updated, rank_path, atol=1e-6, rtol=1e-5)

    text = _render(
        d=d,
        k=k,
        r=r,
        alpha=alpha,
        scaling=scaling,
        w0=w0,
        a_matrix=layer.A.detach(),
        b_before=torch.zeros(d, r),
        b_after=layer.B.detach(),
        x=x,
        y=y,
        base=base,
        initial=initial,
        initial_loss=float(initial_loss),
        diff=diff,
        d_loss_du=d_loss_du,
        z=z,
        a_grad=a_grad,
        b_grad=b_grad,
        hand_a_grad=hand_a_grad,
        hand_b_grad=hand_b_grad,
        updated_delta=updated_delta,
        updated=updated,
        merged_output=merged_output,
    )
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


def _render(**values: object) -> str:
    w0 = values["w0"]
    a_matrix = values["a_matrix"]
    b_before = values["b_before"]
    b_after = values["b_after"]
    x = values["x"]
    y = values["y"]
    base = values["base"]
    initial = values["initial"]
    diff = values["diff"]
    d_loss_du = values["d_loss_du"]
    z = values["z"]
    a_grad = values["a_grad"]
    b_grad = values["b_grad"]
    hand_a_grad = values["hand_a_grad"]
    hand_b_grad = values["hand_b_grad"]
    updated_delta = values["updated_delta"]
    updated = values["updated"]
    merged_output = values["merged_output"]
    d = int(values["d"])
    k = int(values["k"])
    r = int(values["r"])
    alpha = float(values["alpha"])
    scaling = float(values["scaling"])
    initial_loss = float(values["initial_loss"])

    return f"""# Worked numerical example: one LoRA step

_Generated by `report/worked_example.py`. Do not edit manually. Source: {SOURCE}_

The goal is a complete, hand-checkable sequence for
`W' = W0 + (alpha / r) * B @ A`. All matrices are small integers or simple
decimals so every step can be verified manually. The script also checks the
hand-derived gradients against `torch.autograd`.

## 0. Symbols and dimensions

| Symbol | Meaning | Shape | Value |
|---|---|---|---|
| `d` | output dimension | scalar | {d} |
| `k` | input dimension | scalar | {k} |
| `r` | LoRA rank | scalar | {r} |
| `alpha` | LoRA scaling numerator | scalar | {alpha:g} |
| `alpha / r` | scaling applied to `B A` | scalar | {scaling:g} |
| `W0` | frozen base weight | ({d}, {k}) | identity |
| `A` | low-rank factor | ({r}, {k}) | `{_inline(a_matrix)}` |
| `B` | low-rank factor, initialized to zero | ({d}, {r}) | `{_inline(b_before)}` |
| `x` | one input sample (row vector) | (1, {k}) | `{_inline(x)}` |
| `y` | target output | (1, {d}) | `{_inline(y)}` |

Standard LoRA initialization draws `A` from a Gaussian and sets `B = 0`. Here
we choose a simple integer `A` so the arithmetic is easy to check; because
`B = 0`, the initial update `delta = (alpha/r) B A` is still exactly zero.

## 1. Base weight and initial factors

```text
W0 = {_matrix(w0)}
A  = {_matrix(a_matrix)}
B  = {_matrix(b_before)}
```

## 2. Initial update and forward pass

```text
delta = (alpha / r) * B @ A = {_matrix(torch.zeros(d, k).detach())}
h0 = x @ W0.T + (alpha / r) * (x @ A.T) @ B.T
```

Because `B = 0`, the second term is zero:

```text
W0 x^T = {_matrix(base.T)}
h0     = {_matrix(initial.T)}
```

The initial model therefore equals the frozen base model exactly.

## 3. Loss and gradients for one sample

Mean squared error over all `n * d = 1 * {d} = {d}` entries:

```text
L = mean((h0 - y)^2) = {initial_loss:.6f}
h0 - y = {_matrix(diff.T)}
```

The derivative with respect to the pre-activation `u = (alpha/r) B (A x)` is:

```text
dL/du = (2 / (n * d)) * (h0 - y) = {_matrix(d_loss_du.T)}
```

With `z = x @ A.T = {_inline(z)}`:

```text
dL/dB = (alpha/r) * (dL/du).T @ z = {_matrix(b_grad)}
dL/dA = (alpha/r) * ((dL/du @ B).T @ x) = {_matrix(a_grad)}
```

`dL/dA` is exactly zero at initialization because it is multiplied by `B = 0`.
This is the characteristic first-step asymmetry of LoRA.

Autograd check:

```text
torch.autograd dL/dB = {_matrix(b_grad)}
hand-derived   dL/dB = {_matrix(hand_b_grad)}
torch.autograd dL/dA = {_matrix(a_grad)}
hand-derived   dL/dA = {_matrix(hand_a_grad)}
```

The script asserts these are equal within float32 tolerance.

## 4. One SGD step (lr = {LR:g})

```text
B_new = B - lr * dL/dB = {_matrix(b_after)}
A_new = A - lr * dL/dA = {_matrix(a_matrix)}  (unchanged)
```

## 5. New update and effective weight

```text
delta_new = (alpha/r) * B_new @ A_new = {_matrix(updated_delta)}
W' = W0 + delta_new = {_matrix(w0 + updated_delta)}
```

## 6. New forward pass, checked two ways

Dense route:

```text
h = x @ W'.T = {_matrix(updated.T)}
```

Rank-r route:

```text
h = x @ W0.T + (alpha/r) * (x @ A_new.T) @ B_new.T = {_matrix(merged_output.T)}
```

Both routes agree; the script also asserts that `layer.merge()(x)` matches
`layer(x)` after the step.

## 7. Parameter counts for this example

```text
full fine-tuning: d * k          = {d} * {k} = {d * k}
LoRA:             r * (d + k)    = {r} * ({d} + {k}) = {r * (d + k)}
reduction factor: {d * k} / {r * (d + k)} = {(d * k) / (r * (d + k)):.1f}x
```

This toy example is much smaller than a real layer; the reduction factor is
shown only to illustrate the counting formula.
"""


def _matrix(tensor: torch.Tensor) -> str:
    rows = []
    for row in tensor.detach().tolist():
        rows.append("[" + ", ".join(f"{value:.4f}" for value in row) + "]")
    return "\n".join(rows)


def _inline(tensor: torch.Tensor) -> str:
    values = [f"{value:.4f}" for value in tensor.detach().reshape(-1).tolist()]
    return "[" + ", ".join(values) + "]"


if __name__ == "__main__":
    raise SystemExit(main())
