"""Generate ``report/results_summary.md`` from generated raw CSV files.

Only CSV files are read. This is a team toy/synthetic experiment; the text
avoids claiming anything about LLM-scale behaviour.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

from analysis.make_tables import configuration_label, group_runs, read_raw, summarize

SUMMARY_PATH = Path("report/results_summary.md")


def main() -> int:
    """Generate the summary and return a process exit code."""
    lines: list[str] = [
        "# Results summary (auto-generated)",
        "",
        "Generated by `python -m analysis.make_summary` from `results/raw/*.csv`.",
        "Do not edit this file manually; rerun `make assets` instead.",
        "",
        "**Scope:** all numbers below are **Team experiment (toy, synthetic)**.",
        "They are small synthetic regression experiments, not LLM training runs.",
        "",
    ]
    flags: list[str] = []
    lines.extend(_overview())
    lines.extend(_parameter_section())
    exp02 = read_raw("exp02_rank_sweep")
    if exp02 is not None:
        lines.extend(_main_results(exp02, flags))
    exp03 = read_raw("exp03_fullrank_target")
    if exp03 is not None:
        lines.extend(_limitation_results(exp03, flags))
    exp04 = read_raw("exp04_merge_check")
    if exp04 is not None:
        lines.extend(_merge_results(exp04, flags))
    exp05 = read_raw("exp05_alpha_scaling")
    if exp05 is not None:
        lines.extend(_alpha_results(exp05))
    exp06 = read_raw("exp06_qlora_sim")
    if exp06 is not None:
        lines.extend(_qlora_results(exp06, flags))

    lines.extend(_flags_section(flags))
    lines.extend(_limitations_section())
    SUMMARY_PATH.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {SUMMARY_PATH}")
    return 0


def _overview() -> list[str]:
    df = read_raw("exp02_rank_sweep")
    if df is None:
        return ["## Setup", "", "No exp02 raw CSV found yet.", ""]
    first = df.iloc[0]
    seeds = sorted({int(value) for value in df["seed"]})
    return [
        "## Setup",
        "",
        f"- Layer size: d = {int(first['d'])}, k = {int(first['k'])}.",
        f"- Training epochs: {int(first['epochs'])}; seeds: {seeds}.",
        f"- Target: `{first['target']}`; quantizer: `{first['quantizer']}`.",
        "- Learning rates are selected on the validation split; metrics are "
        "reported on the test split.",
        "",
    ]


def _parameter_section() -> list[str]:
    df = read_raw("exp01_param_table")
    if df is None:
        return []
    rows = []
    memory: dict[str, int] = {}
    for _, row in df.iterrows():
        hparams = json.loads(row["method_hparams"])
        extra = json.loads(row["extra"])
        label = configuration_label(row["method"], hparams)
        rows.append((label, int(row["trainable_params"]), int(row["total_params"])))
        memory[label] = int(extra["memory_total_bytes"])
    lines = [
        "## D1/D2 - Parameters versus analytical memory",
        "",
        "| Configuration | Trainable parameters | Full FT parameters | Analytical total bytes |",
        "|---|---|---|---|",
    ]
    for label, trainable, total in rows:
        lines.append(f"| {label} | {trainable:,} | {total:,} | {memory[label]:,} |")
    lines.extend(
        [
            "",
            "These memory numbers are analytical and exclude activations; they are "
            "not measured GPU memory. See `results/tables/param_table.md` and "
            "`results/tables/memory_estimate.md`.",
            "",
        ]
    )
    return lines


def _main_results(df, flags: list[str]) -> list[str]:
    groups = group_runs(df)
    stats = _stats(groups)
    rows = sorted(stats.values(), key=_row_order)
    lines = [
        "## D5 - Rank sweep versus full fine-tuning (`exp02`)",
        "",
        "| Configuration | Trainable params | Test MSE (mean +/- std) | "
        "Rel. delta error (mean +/- std) | Mean selected lr |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['label']} | {row['params']:,} | "
            f"{_mean_std(row['test_mean'], row['test_std'])} | "
            f"{_mean_std(row['rel_mean'], row['rel_std'])} | "
            f"{_lr(row['lr_mean'])} |"
        )
    lines.append("")

    lora = [row for row in stats.values() if row["method"] == "lora"]
    full = _find(stats.values(), method="full_ft", trained=True)
    no_ft = _find(stats.values(), method="full_ft", trained=False)
    if lora and full:
        best = min(lora, key=lambda row: _nan_to_inf(row["test_mean"]))
        lines.extend(
            [
                "**Observed in this setup:** "
                f"best LoRA is `{best['label']}` with test MSE "
                f"{best['test_mean']:.3e} versus full fine-tuning at "
                f"{full['test_mean']:.3e}.",
            ]
        )
        if best["test_mean"] < full["test_mean"]:
            lines.append(
                "LoRA performed better than full fine-tuning here. This is likely "
                "an optimization/regularization effect in the toy problem, not a "
                "general claim about LoRA."
            )
            flags.append(
                "Best LoRA test MSE was lower than full fine-tuning in exp02; the "
                "summary reports this instead of forcing the expected ordering."
            )
        else:
            lines.append(
                "Full fine-tuning matched or beat the best LoRA rank here, "
                "consistent with the expected trade-off."
            )
        small = [row for row in lora if row["rank"] in {1, 2, 4}]
        high = [row for row in lora if row["rank"] == 8]
        if small and high:
            worst_small = max(small, key=lambda row: _nan_to_inf(row["test_mean"]))
            lines.append(
                f"Rank {worst_small['rank']} had test MSE "
                f"{worst_small['test_mean']:.3e}, while rank 8 had "
                f"{high[0]['test_mean']:.3e}; ranks below the true rank underfit "
                "in this setup."
            )
    if no_ft:
        lines.append(
            f"The no-fine-tuning baseline (delta = 0) had test MSE {no_ft['test_mean']:.3e}."
        )
    lines.append("")
    return lines


def _limitation_results(df, flags: list[str]) -> list[str]:
    groups = group_runs(df)
    stats = _stats(groups)
    gammas = sorted({row["gamma"] for row in stats.values() if row["gamma"] is not None})
    lines = [
        "## D6 - Full-rank target limitation (`exp03`)",
        "",
        "| Gamma | Best LoRA | Best LoRA test MSE | Full FT test MSE | Gap (LoRA - full FT) |",
        "|---|---|---|---|---|",
    ]
    for gamma in gammas:
        lora = [row for row in stats.values() if row["gamma"] == gamma and row["method"] == "lora"]
        full = _find(
            [row for row in stats.values() if row["gamma"] == gamma],
            method="full_ft",
            trained=True,
        )
        if not lora or full is None:
            continue
        best = min(lora, key=lambda row: _nan_to_inf(row["test_mean"]))
        gap = best["test_mean"] - full["test_mean"]
        lines.append(
            f"| {gamma:g} | {best['label']} | {best['test_mean']:.3e} | "
            f"{full['test_mean']:.3e} | {gap:+.3e} |"
        )
        if gap < 0:
            flags.append(
                f"At gamma={gamma:g}, LoRA beat full fine-tuning in exp03; this "
                "does not support the expected limitation ordering."
            )
    lines.extend(
        [
            "",
            "Small rank cannot represent a long spectral tail in principle. The "
            "table reports what was measured; the toy optimization dynamics can "
            "differ from that intuition.",
            "",
        ]
    )
    return lines


def _merge_results(df, flags: list[str]) -> list[str]:
    groups = group_runs(df)
    stats = _stats(groups)
    lines = [
        "## D7 - Numerical merge check (`exp04`)",
        "",
        "| Configuration | Max abs error | Threshold | Passes |",
        "|---|---|---|---|",
    ]
    for row in sorted(stats.values(), key=_row_order):
        items = groups[row["key"]]
        max_error = max(item["merge_max_abs_err"] for item in items)
        tolerance = items[0]["merge_tolerance"]
        ok = all(item["merge_ok"] for item in items)
        lines.append(
            f"| {row['label']} | {max_error:.3e} | {tolerance:.1e} | {'yes' if ok else 'NO'} |"
        )
        if not ok:
            flags.append(f"Merge check failed for {row['label']}.")
    lines.extend(
        [
            "",
            "Merging replaces the rank-r forward path with one dense `nn.Linear`, "
            "so inference has no adapter latency.",
            "",
        ]
    )
    return lines


def _alpha_results(df) -> list[str]:
    stats = _stats(group_runs(df))
    modes = sorted({row["lr_selection"] for row in stats.values() if row["lr_selection"]})
    lines = ["## Optional exp05 - Alpha scaling", ""]
    for mode in modes:
        subset = [row for row in stats.values() if row["lr_selection"] == mode]
        if not subset:
            continue
        best = min(subset, key=lambda row: _nan_to_inf(row["test_mean"]))
        lines.append(
            f"- `{mode}` learning rate: best `{best['label']}` at test MSE {best['test_mean']:.3e}."
        )
    lines.append("")
    return lines


def _qlora_results(df, flags: list[str]) -> list[str]:
    groups = group_runs(df)
    stats = _stats(groups)
    quantizers = sorted({row["quantizer"] for row in stats.values()})
    lines = [
        "## Optional exp06 - Simulated QLoRA",
        "",
        "**Important:** this is simple absmax block 4-bit quantization, **not NF4**.",
        "",
        "| Quantizer | Best LoRA | Best LoRA test MSE | Mean quant. error |",
        "|---|---|---|---|",
    ]
    for quantizer in quantizers:
        lora = [
            row
            for row in stats.values()
            if row["quantizer"] == quantizer and row["method"] == "lora"
        ]
        if not lora:
            continue
        best = min(lora, key=lambda row: _nan_to_inf(row["test_mean"]))
        quant_error = _mean_of([item["quant_error"] for item in groups[best["key"]]])
        lines.append(
            f"| {quantizer} | {best['label']} | {best['test_mean']:.3e} | {quant_error:.3e} |"
        )
    lines.extend(
        [
            "",
            "The table compares a full-precision base with a simple 4-bit base. It "
            "does not establish that QLoRA fully recovers the original model.",
            "",
        ]
    )
    if any(row["quantizer"] != "none" for row in stats.values()):
        flags.append(
            "exp06 is a simulated 4-bit experiment (absmax block), not NF4 and not an LLM run."
        )
    return lines


def _flags_section(flags: list[str]) -> list[str]:
    lines = ["## Result flags", ""]
    if not flags:
        lines.append("- No contradictions were detected automatically.")
    else:
        for flag in flags:
            lines.append(f"- {flag}")
    lines.append("")
    return lines


def _limitations_section() -> list[str]:
    return [
        "## Limitations",
        "",
        "- Data, base weights, and targets are synthetic; this is a toy problem.",
        "- Scale is small (see the setup table), far below any LLM.",
        "- CPU toy timings are not representative of real training hardware.",
        "- Memory numbers are analytical estimates and exclude activations.",
        "- Simulated QLoRA uses simple absolute-max 4-bit quantization, not NF4.",
        "- Results are conditional on the chosen model class, optimizer, and grids; "
        "they do not generalize to LLMs.",
        "",
    ]


def _stats(groups: dict[tuple[str, ...], list[dict[str, Any]]]) -> dict[str, dict[str, Any]]:
    result: dict[str, dict[str, Any]] = {}
    for key, items in groups.items():
        first = items[0]
        test_mean, test_std = summarize([item["test_mse"] for item in items])
        rel_mean, rel_std = summarize([item["rel_delta_err"] for item in items])
        lr_mean, _ = summarize([item["lr"] for item in items])
        hparams = first["hparams"]
        result[str(key)] = {
            "key": key,
            "label": configuration_label(first["method"], hparams),
            "method": first["method"],
            "quantizer": first["quantizer"],
            "gamma": first["target_cfg"].get("gamma"),
            "rank": hparams.get("r", -1),
            "alpha": hparams.get("alpha", -1),
            "lr_selection": hparams.get("lr_selection", ""),
            "trained": hparams.get("trained", True),
            "params": first["trainable_params"],
            "test_mean": test_mean,
            "test_std": test_std,
            "rel_mean": rel_mean,
            "rel_std": rel_std,
            "lr_mean": lr_mean,
        }
    return result


def _find(rows: Any, *, method: str, trained: bool) -> dict[str, Any] | None:
    for row in rows:
        if row["method"] == method and bool(row["trained"]) == trained:
            return row
    return None


def _row_order(row: dict[str, Any]) -> tuple[int, float, float, str]:
    if row["method"] == "full_ft" and row["trained"] is False:
        group = 0
    elif row["method"] == "full_ft":
        group = 1
    else:
        group = 2
    rank = row["rank"] if isinstance(row["rank"], (int, float)) else -1
    alpha = row["alpha"] if isinstance(row["alpha"], (int, float)) else -1
    return (group, float(rank), float(alpha), str(row["lr_selection"]))


def _nan_to_inf(value: float) -> float:
    return float("inf") if math.isnan(value) else value


def _mean_std(mean: float, std: float) -> str:
    if math.isnan(mean):
        return "n/a"
    return f"{mean:.3e} +/- {std:.3e}"


def _lr(value: float) -> str:
    if math.isnan(value):
        return "n/a"
    return f"{value:g}"


def _mean_of(values: list[float]) -> float:
    clean = [value for value in values if value is not None and not math.isnan(value)]
    return sum(clean) / len(clean) if clean else float("nan")


if __name__ == "__main__":
    raise SystemExit(main())
